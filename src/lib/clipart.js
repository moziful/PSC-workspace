export function getClipartById(id) {
  if (!id) return null;
  return CLIPART_LIBRARY[id.toLowerCase()] || null;
}

export function searchClipart(query) {
  if (!query) return null;
  const lower = query.toLowerCase();
  for (const item of Object.values(CLIPART_LIBRARY)) {
    if (
      item.id === lower ||
      item.nameEnglish.toLowerCase() === lower ||
      item.nameBangla === lower ||
      item.tags.some(tag => lower.includes(tag) || tag.includes(lower))
    ) {
      return item;
    }
  }
  return null;
}
